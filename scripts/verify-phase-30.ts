#!/usr/bin/env tsx
/**
 * verify-phase-30.ts — Phase 30 (Plan 01 + Plan 02) verification runner.
 *
 * Project convention (Pitfalls B3): no vitest/jest. This standalone `tsx`
 * script follows the `scripts/verify-phase-29.ts` pattern:
 *   - a local `assert()` helper pushes to a `results` array
 *   - a `main()` async function sums pass/fail and exits 1 on any failure
 *   - `main().catch(err => process.exit(2))` on uncaught exception
 *
 * Phase 30 success criteria (from ROADMAP + plan):
 *   1. (SC #1) Empty-DB boot → GET /api/v1/skills returns [movie-v1] summary.
 *   2. (SC #2) POST /register valid → 201, persisted, cache updated, retrievable.
 *   3. (SC #3) POST /register malformed → 400 with structured errors, no mutation.
 *   4. (SC #4) GET /node-types + /phases return declared arrays verbatim.
 *   5. (SC #5) Manifest derived from constants (spot-check 3 phases).
 *
 * Also closes API-01..API-05 (API-06 closed by Plan 30-01's boot wiring).
 *
 * Pitfalls B5 (ESM/CJS interop): the runner is invoked via
 * `tsx scripts/verify-phase-30.ts`. It is a standalone .ts file — NOT `tsx -e`.
 *
 * IMPORTANT SIDE-EFFECT NOTE:
 * The 5 route files (list/get/register/node-types/phases) import dependencies
 * that transitively reach `@/utils` → `@/utils/db.ts`, whose module body runs
 * an IIFE that initializes db2.sqlite + runs migrations + seeds movie-v1.
 * This means importing the route files triggers the real boot path. Two
 * consequences:
 *
 *   1. The singleton `u.db` is initialized at module load. Test 5 (malformed
 *      register) invokes the real register handler via Express — but since
 *      validateManifest fails BEFORE any `u.db(...)` call, the singleton db
 *      is never touched by the malformed test path.
 *
 *   2. movie-v1 may already be in the registry cache by the time main() runs,
 *      because seedDefaultIfEmpty ran as part of the @/utils/db IIFE.
 *      Test assertions are written to be order-independent for this reason
 *      (e.g., list length is checked `>= 1`, not `=== 1`).
 *
 * Test 6 (valid register) uses Option A (indirect) — it does NOT invoke the
 * real register handler (which would call the singleton db). It replicates
 * the handler's flow against a transient :memory: Knex instance. This keeps
 * the valid-register test hermetic.
 *
 * Usage:
 *   tsx scripts/verify-phase-30.ts
 *
 * Exit codes:
 *   0 — all assertions pass
 *   1 — one or more assertions failed (structured detail logged)
 *   2 — uncaught exception (test infrastructure bug)
 */

